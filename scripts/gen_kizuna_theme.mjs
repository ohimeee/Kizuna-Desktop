// Generates src/lib/theme/kizuna.ts: Kizuna's own theme, a Material 3 scheme built from the
// brand colours (assets/icon.svg and the splash):
//   peach-pink  #EF98A6  (splash)      -> primary, the main colour
//   dusty pink  same family, quieter    -> secondary (a darker peach turns brown in dark mode)
//   mint        opposite pink on the wheel -> tertiary, the complement
//   ink         #031019  (the 絆 mark)  -> dark-mode surfaces (navy pairs with pink)
//   blush       #FFD6DB  (icon fill)    -> tints the light-mode whites
//
//   node scripts/gen_kizuna_theme.mjs
// Uses @material/material-color-utilities 0.3.0 from the global npm folder (0.4.0 has a broken
// internal import).
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = execSync("npm root -g").toString().trim();
const mcu = await import(pathToFileURL(join(root, "@material/material-color-utilities/index.js")).href);
const { Hct, TonalPalette, DynamicScheme, MaterialDynamicColors: C, hexFromArgb, argbFromHex } = mcu;
// 0.3.0's index doesn't re-export Variant.
const { Variant } = await import(pathToFileURL(join(root, "@material/material-color-utilities/dynamiccolor/variant.js")).href);

const PINK = Hct.fromInt(argbFromHex("#EF98A6"));
const INK = Hct.fromInt(argbFromHex("#031019"));
const BLUSH = Hct.fromInt(argbFromHex("#FFD6DB"));
const wrap = (h) => ((h % 360) + 360) % 360;

const palettes = (dark) => ({
  // Peach-pink: the splash pink nudged warmer, vivid enough to read as pink at every tone.
  primaryPalette: TonalPalette.fromHueAndChroma(wrap(PINK.hue + 6), 58),
  // Dusty rose, a touch cooler than the primary: warm hues go brown at dark container tones.
  secondaryPalette: TonalPalette.fromHueAndChroma(wrap(PINK.hue - 8), 26),
  // Mint, the complement of pink.
  tertiaryPalette: TonalPalette.fromHueAndChroma(wrap(PINK.hue + 180), 32),
  // Surfaces: ink-navy in dark mode, blush-warm in light mode.
  neutralPalette: dark ? TonalPalette.fromHueAndChroma(INK.hue, 7) : TonalPalette.fromHueAndChroma(BLUSH.hue, 5),
  neutralVariantPalette: dark ? TonalPalette.fromHueAndChroma(INK.hue, 12) : TonalPalette.fromHueAndChroma(BLUSH.hue, 12),
});

const KEYS = {
  primary: C.primary, "on-primary": C.onPrimary, "primary-container": C.primaryContainer,
  "on-primary-container": C.onPrimaryContainer, "inverse-primary": C.inversePrimary,
  secondary: C.secondary, "on-secondary": C.onSecondary, "secondary-container": C.secondaryContainer,
  "on-secondary-container": C.onSecondaryContainer,
  tertiary: C.tertiary, "on-tertiary": C.onTertiary, "tertiary-container": C.tertiaryContainer,
  "on-tertiary-container": C.onTertiaryContainer,
  error: C.error, "on-error": C.onError, "error-container": C.errorContainer, "on-error-container": C.onErrorContainer,
  background: C.background, "on-background": C.onBackground, surface: C.surface, "on-surface": C.onSurface,
  "surface-variant": C.surfaceVariant, "on-surface-variant": C.onSurfaceVariant, "surface-tint": C.surfaceTint,
  "inverse-surface": C.inverseSurface, "inverse-on-surface": C.inverseOnSurface,
  outline: C.outline, "outline-variant": C.outlineVariant, scrim: C.scrim,
  "surface-dim": C.surfaceDim, "surface-bright": C.surfaceBright,
  "surface-container-lowest": C.surfaceContainerLowest, "surface-container-low": C.surfaceContainerLow,
  "surface-container": C.surfaceContainer, "surface-container-high": C.surfaceContainerHigh,
  "surface-container-highest": C.surfaceContainerHighest,
};

function scheme(dark) {
  const s = new DynamicScheme({ sourceColorArgb: PINK.toInt(), variant: Variant.TONAL_SPOT, contrastLevel: 0, isDark: dark, ...palettes(dark) });
  return Object.fromEntries(Object.entries(KEYS).map(([k, c]) => [k, hexFromArgb(c.getArgb(s))]));
}

const dark = scheme(true);
const light = scheme(false);
const out = join(dirname(fileURLToPath(import.meta.url)), "../src/lib/theme/kizuna.ts");
writeFileSync(
  out,
  `// Generated by scripts/gen_kizuna_theme.mjs from the Kizuna brand colours. Do not edit.
import type { AppTheme } from "./themes";

export const KIZUNA: AppTheme = {
  id: "kizuna",
  label: "Kizuna (Default)",
  dark: ${JSON.stringify(dark)},
  light: ${JSON.stringify(light)},
};
`,
);
console.log("wrote", out);
for (const k of ["primary", "primary-container", "secondary-container", "tertiary", "background", "surface-container"]) {
  console.log(k.padEnd(20), "dark", dark[k], " light", light[k]);
}
