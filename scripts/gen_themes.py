"""Generates src/lib/theme/themes.ts from the Android app's Kotlin color schemes.

    python scripts/gen_themes.py D:/Coding/Kizuna
"""
import json, re, sys
from pathlib import Path

root = Path(sys.argv[1]) / "app/src/main/java/eu/kanade/presentation/theme/colorscheme"
out = Path(__file__).resolve().parent.parent / "src/lib/theme/themes.ts"

def camel_to_kebab(s): return re.sub(r"(?<!^)(?=[A-Z])", "-", s).lower()

themes = {}
for f in sorted(root.glob("*ColorScheme.kt")):
    name = f.stem.replace("ColorScheme", "")
    if name in ("Base", "Monet"):
        continue
    text = f.read_text(encoding="utf-8")
    schemes = {}
    for mode in ("dark", "light"):
        m = re.search(rf"{mode}Scheme\s*=\s*{mode}ColorScheme\((.*?)\n\s*\)", text, re.S)
        if not m:
            continue
        colors = {}
        for key, hexv in re.findall(r"(\w+)\s*=\s*Color\(0x([0-9A-Fa-f]{8})\)", m.group(1)):
            colors[camel_to_kebab(key)] = "#" + hexv[2:].lower()
        schemes[mode] = colors
    if schemes:
        themes[re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()] = schemes

labels = {k: k.replace("-", " ").title() for k in themes}
labels.update({"tachiyomi": "Default", "green-apple": "Green Apple", "midnight-dusk": "Midnight Dusk"})
order = ["tachiyomi"] + sorted(k for k in themes if k != "tachiyomi")
ts = ["// Generated by scripts/gen_themes.py from the Android app's color schemes. Do not edit.",
      "export type Scheme = Record<string, string>;",
      "export interface AppTheme { id: string; label: string; dark: Scheme; light: Scheme }",
      "export const THEMES: AppTheme[] = ["]
for k in order:
    ts.append(f"  {{ id: {json.dumps(k)}, label: {json.dumps(labels[k])}, dark: {json.dumps(themes[k]['dark'])}, light: {json.dumps(themes[k]['light'])} }},")
ts.append("];")
out.write_text("\n".join(ts) + "\n", encoding="utf-8")
print("wrote", out, "themes:", order, "keys:", len(themes["tachiyomi"]["dark"]))
