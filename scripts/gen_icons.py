"""Generates src/lib/components/icons.ts: imports only the Material Symbols the app uses.
Add a name to NAMES and re-run:  python scripts/gen_icons.py"""
from pathlib import Path
NAMES = """local_library release_alert history explore more_horiz settings search close arrow_back refresh
favorite filter_list sort check done_all bookmark lock download delete add edit extension public open_in_new
chevron_left chevron_right keyboard_arrow_up keyboard_double_arrow_up vertical_align_top format_list_bulleted
text_fields format_align_left format_align_center format_align_justify format_align_right palette info label
drag_indicator arrow_upward arrow_downward more_vert error check_circle travel_explore update menu_book
visibility visibility_off remove_done select_all light_mode dark_mode contrast fullscreen fullscreen_exit tune
schedule battery_full language keyboard_arrow_down cancel warning folder sync play_arrow skip_previous
skip_next list format_size line_weight padding width_normal auto_stories circle radio_button_unchecked
category new_label upload restart_alt my_location battery_5_bar""".split()
root = Path(__file__).resolve().parent.parent
svgdir = root / "node_modules/@material-symbols/svg-400/rounded"
lines = ["// Generated by scripts/gen_icons.py. Do not edit.", ""]
entries = []
for i, n in enumerate(sorted(set(NAMES))):
    for variant in (n, n + "-fill"):
        if (svgdir / f"{variant}.svg").exists():
            var = "i" + str(len(entries))
            lines.append(f'import {var} from "@material-symbols/svg-400/rounded/{variant}.svg?raw";')
            entries.append((variant, var))
        elif variant == n:
            raise SystemExit(f"missing icon: {n}")
lines += ["", "export const ICONS: Record<string, string> = {"]
lines += [f'  "{k}": {v},' for k, v in entries]
lines += ["};", ""]
(root / "src/lib/components/icons.ts").write_text("\n".join(lines), encoding="utf-8")
print(len(entries), "icon files")
